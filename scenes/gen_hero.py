# emits the hero scene .test file. room with a window wall, bright quad light outside,
# foggy interior. edit the params block and rerun.
# corners of each quad are given counterclockwise as seen from inside the room
# so tri normals point inward (the renderer does not flip normals).

import sys

# ---- params ----
OUT = "hero.test"
W, H = 800, 800
SPP = 4096

# room: x in [-6,6], y in [0,8], z in [-6,6]. window wall at x=-6.
X0, X1 = -6.0, 6.0
Y0, Y1 = 0.0, 8.0
Z0, Z1 = -6.0, 6.0

# window opening in the x=-6 wall
WY0, WY1 = 2.5, 6.0
WZ0, WZ1 = -3.0, 1.0
MULL = 0.22           # mullion half-width
MULL_Z = -1.0         # vertical mullion at this z
MULL_Y = 4.25         # horizontal mullion at this y

# light: quad outside, high up, so the beam slants down into the room
LPOS = (-26.0, 22.0)   # x and y center of the light
LSIZE = 1.5           # half-size
LZ0, LZ1 = WZ0 - 0.5, WZ1 + 0.5
LINT = (6800, 6360, 5400)   # warm

# camera: inside, viewing the window wall at an angle (side-on to the beam)
EYE = (4.4, 3.4, 3.8)
LOOKAT = (-3.2, 2.2, -2.4)
FOVY = 60

# medium
SIGMA_A = (0.02, 0.02, 0.02)
SIGMA_S = (0.075, 0.075, 0.075)
G = 0.45

# sphere in the beam landing zone
SPH = (-0.8, 1.05, -1.5, 1.05)   # x y z radius

verts = []
tris = []

def vid(v):
    verts.append(v)
    return len(verts) - 1

def quad(a, b, c, d):
    # a,b,c,d counterclockwise from inside
    ia, ib, ic, id_ = vid(a), vid(b), vid(c), vid(d)
    tris.append((ia, ib, ic))
    tris.append((ia, ic, id_))

geom = []   # (material dict, list of quads) groups, emitted in order

def group(mat, quads):
    geom.append((mat, list(quads)))

# floor (normal +y): ccw from above
group({"diffuse": (0.22, 0.19, 0.16), "specular": (0, 0, 0)}, [
    ((X0, Y0, Z1), (X1, Y0, Z1), (X1, Y0, Z0), (X0, Y0, Z0)),
])
# ceiling (normal -y)
group({"diffuse": (0.13, 0.13, 0.15), "specular": (0, 0, 0)}, [
    ((X0, Y1, Z0), (X1, Y1, Z0), (X1, Y1, Z1), (X0, Y1, Z1)),
])
# back wall z=Z0 (normal +z)
group({"diffuse": (0.14, 0.14, 0.16), "specular": (0, 0, 0)}, [
    ((X0, Y0, Z0), (X1, Y0, Z0), (X1, Y1, Z0), (X0, Y1, Z0)),
])
# right wall x=X1 (normal -x)
group({"diffuse": (0.15, 0.14, 0.13), "specular": (0, 0, 0)}, [
    ((X1, Y0, Z0), (X1, Y0, Z1), (X1, Y1, Z1), (X1, Y1, Z0)),
])
# front wall z=Z1 behind the camera (normal -z). keeps the room closed for bounce light.
group({"diffuse": (0.14, 0.14, 0.16), "specular": (0, 0, 0)}, [
    ((X1, Y0, Z1), (X0, Y0, Z1), (X0, Y1, Z1), (X1, Y1, Z1)),
])

# window wall x=X0 (normal +x), four strips around the opening plus mullions
wall = {"diffuse": (0.12, 0.12, 0.13), "specular": (0, 0, 0)}
def wallquad(y0, y1, z0, z1):
    # ccw seen from inside (+x side): z decreasing is "to the right" when looking at -x...
    # order: (z1,y0) (z0,y0) (z0,y1) (z1,y1) gives normal +x
    return ((X0, y0, z1), (X0, y0, z0), (X0, y1, z0), (X0, y1, z1))

strips = [
    wallquad(Y0, WY0, Z0, Z1),     # bottom
    wallquad(WY1, Y1, Z0, Z1),     # top
    wallquad(WY0, WY1, Z0, WZ0),   # left of opening
    wallquad(WY0, WY1, WZ1, Z1),   # right of opening
    # mullions: thin strips across the opening
    wallquad(WY0, WY1, MULL_Z - MULL, MULL_Z + MULL),
    wallquad(MULL_Y - MULL, MULL_Y + MULL, WZ0, WZ1),
]
group(wall, strips)

# ---- emit ----
lines = []
a = lines.append
a("# hero scene: light shafts through a window into a foggy room")
a("# generated by gen_hero.py, edit params there not here")
a(f"size {W} {H}")
a("integrator pathtracer")
a(f"spp {SPP}")
a("importancesampling brdf")
a("nexteventestimation mis")
a("russianroulette on")
a("maxdepth -1")
a("gamma 2.2")
a("output hero.png")
a("")
a(f"camera {EYE[0]} {EYE[1]} {EYE[2]} {LOOKAT[0]} {LOOKAT[1]} {LOOKAT[2]} 0 1 0 {FOVY}")
a("")
a(f"sigma_a {SIGMA_A[0]} {SIGMA_A[1]} {SIGMA_A[2]}")
a(f"sigma_s {SIGMA_S[0]} {SIGMA_S[1]} {SIGMA_S[2]}")
a(f"g {G}")
a("")
lx, ly = LPOS
a("# light outside the window, ab along z, ac tilted down toward the opening")
a(f"quadLight {lx} {ly - LSIZE} {LZ0}  0 0 {LZ1 - LZ0}  {2.0} {2.0 * LSIZE} 0  {LINT[0]} {LINT[1]} {LINT[2]}")
a("")

# geometry
nv = sum(len(q) * 4 for _, q in geom)
a(f"maxverts {nv}")
for mat, quads in geom:
    a("")
    d = mat["diffuse"]; s = mat["specular"]
    a(f"diffuse {d[0]} {d[1]} {d[2]}")
    a(f"specular {s[0]} {s[1]} {s[2]}")
    a("emission 0 0 0")
    a("ambient 0 0 0")
    base = len(verts)
    start_tri = len(tris)
    for q in quads:
        quad(*q)
    for v in verts[base:]:
        a(f"vertex {v[0]} {v[1]} {v[2]}")
    for t in tris[start_tri:]:
        a(f"tri {t[0]} {t[1]} {t[2]}")

a("")
a("# ggx sphere in the beam landing zone")
a("brdf ggx")
a("diffuse 0.20 0.19 0.21")
a("specular 0.65 0.62 0.58")
a("roughness 0.18")
a("emission 0 0 0")
a("ambient 0 0 0")
a(f"sphere {SPH[0]} {SPH[1]} {SPH[2]} {SPH[3]}")

open(OUT, "w").write("\n".join(lines) + "\n")
print(f"wrote {OUT}: {len(verts)} verts, {len(tris)} tris")